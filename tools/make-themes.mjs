// Generates src/theme.css (default palette, all intensity levels) and src/palettes.css
// (the other palettes, scoped to :root[data-palette="…"]) with the Material Next theme generator.
// Usage: node tools/make-themes.mjs [path/to/mn.mjs]
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';

const MN = process.argv[2] || process.env.MN_BUNDLER || `${homedir()}/.claude/skills/material-next/scripts/mn.mjs`;
const DEFAULT = 'bloom';
const PALETTES = ['tide', 'aurora', 'citrus', 'nocturne', 'graphite'];
const gen = mood => execFileSync('node', [MN, 'theme', 'Pagewise', `--mood=${mood}`, '--levels=all'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });

// Default palette: keep the app-accent block that lives at the end of theme.css
const current = readFileSync('src/theme.css', 'utf8');
const accents = current.slice(current.indexOf('/* ---- App accents'));
writeFileSync('src/theme.css', gen(DEFAULT).trimEnd() + '\n\n' + accents);

// Other palettes: colour blocks only, scoped by data-palette
let out = '/* Extra palettes for Pagewise, generated by tools/make-themes.mjs. Material Next design language:\n   independent, built on M3; not an official Google design. */\n';
// Preview chips for the Appearance picker: primary, primary-container, tertiary-container (light scheme)
const pick = (css, name) => (css.match(new RegExp(`--md-sys-color-${name}:\\s*(#[0-9A-Fa-f]{6})`)) || [])[1];
let previews = '\n/* ---- Picker previews ---- */\n';
for (const mood of [DEFAULT, ...PALETTES]) {
  const css = gen(mood);
  previews += `.pal[data-pick="${mood}"] { --p1: ${pick(css, 'primary')}; --p2: ${pick(css, 'primary-container')}; --p3: ${pick(css, 'tertiary-container')}; --p4: ${pick(css, 'secondary-container')}; }\n`;
}
out += previews;
for (const mood of PALETTES) {
  const css = gen(mood);
  const lines = css.split('\n');
  const blocks = [];
  let buf = null, depth = 0, keep = false;
  for (const line of lines) {
    if (buf === null) {
      if (/^(:root|@media \(prefers-color-scheme: dark\))/.test(line)) { buf = [line]; depth = (line.match(/\{/g) || []).length - (line.match(/\}/g) || []).length; keep = true; }
      continue;
    }
    buf.push(line);
    depth += (line.match(/\{/g) || []).length - (line.match(/\}/g) || []).length;
    if (depth <= 0) { if (keep) blocks.push(buf.join('\n')); buf = null; }
  }
  const scoped = blocks
    .filter(b => /--md-sys-color-primary:/.test(b))
    .map(b => b.replace(/:root/g, `:root[data-palette="${mood}"]`).replace(/^\s*transition:[\s\S]*?;\n/m, '').replace(/^\s*--mn-.*\n/gm, ''));
  out += `\n/* ---- ${mood} ---- */\n` + scoped.join('\n') + '\n';
}
writeFileSync('src/palettes.css', out);
console.log('wrote src/theme.css and src/palettes.css');
